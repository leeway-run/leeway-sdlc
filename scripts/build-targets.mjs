// Builds the package for agents other than Claude Code from plugin/, and the onboarding page.
//
//   node scripts/build-targets.mjs           write targets/agents/ and agent-setup/prompt.md
//   node scripts/build-targets.mjs --check   build to a temp dir and fail if the committed copies differ
//
// plugin/ stays the one source and the Claude Code plugin. targets/agents/ is generated and committed,
// because every agent installs straight from git. Its layout:
//
//   targets/agents/
//     plugin.json, README.md, HARNESS.md        the package (Copilot and Codex read plugin.json)
//     skills/<skill>/SKILL.md ...               plugin/skills with a header saying where the plugin's files are
//     skills/sdlc-install/kit/                  what sdlc-install copies to .sdlc/kit/ in the repo:
//       PROCESS.md, HARNESS.md, craft/, agents/, skills/ (the skills' files but not SKILL.md, for "in this plugin" paths)
//       hooks/git-guard.mjs, hooks/leeway-guard.mjs, hooks/adapters/{guard,governed}.mjs
//       harness/<agent>.md                      one HARNESS.md per agent (scripts/targets.mjs)
//       wiring/<agent>/...                      that agent's subagents and guard hook, at their repo paths
//
// No dependencies.

import { cpSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import { harness, TARGETS } from './targets.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const PLUGIN = join(ROOT, 'plugin')
const check = process.argv.includes('--check')

// Shown wherever someone using an agent other than Claude Code will look first.
export const NOTICE =
  '> **Tested with Claude Code only.** Support for other agents is built in but has not been verified yet. ' +
  'Verified support will come later. If you run into an issue, let us know: https://github.com/leeway-run/leeway-sdlc/issues'

const version = JSON.parse(readFileSync(join(PLUGIN, '.claude-plugin', 'plugin.json'), 'utf8')).version
const claudeHarnessVersion = /^version:\s*(\S+)/m.exec(readFileSync(join(PLUGIN, 'HARNESS.md'), 'utf8'))?.[1]
if (claudeHarnessVersion !== version) {
  console.error(`plugin/HARNESS.md version ${claudeHarnessVersion} != plugin.json ${version}`)
  process.exit(1)
}

const write = (path, content) => {
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, content)
}
const files = (dir) =>
  existsSync(dir)
    ? readdirSync(dir).flatMap((n) => (statSync(join(dir, n)).isDirectory() ? files(join(dir, n)) : [join(dir, n)]))
    : []
const posix = (p) => p.split(sep).join('/')

// plugin/agents/<name>.md → { name, description, readOnly, body }.
const parseAgent = (path) => {
  const text = readFileSync(path, 'utf8').replace(/\r\n/g, '\n')
  const m = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(text)
  if (!m) throw new Error(`${path}: no frontmatter`)
  const front = Object.fromEntries(
    m[1].split('\n').map((l) => {
      const i = l.indexOf(':')
      return [l.slice(0, i).trim(), l.slice(i + 1).trim()]
    }),
  )
  const tools = (front.tools ?? '').split(',').map((t) => t.trim())
  return { name: front.name, description: front.description, readOnly: !tools.includes('Edit') && !tools.includes('Write'), body: m[2] }
}

const SKILL_HEADER = `> **leeway-sdlc for agents other than Claude Code.** This plugin's files (\`PROCESS.md\`, \`HARNESS.md\`, \`craft/\`,
> \`agents/\`, \`hooks/\` and the skills' own files) are in **\`.sdlc/kit/\`** at the repo root once \`sdlc-install\` has
> run: "in this plugin" below means there, except that \`skills/<name>/SKILL.md\` is the \`<name>\` skill itself
> (load it as a skill; its other files are in \`.sdlc/kit/skills/<name>/\`). Read \`.sdlc/kit/HARNESS.md\` for how this agent delegates, marks a
> subagent's run and updates. With no \`.sdlc/kit/\` yet, run \`sdlc-install\` first; it reads them from its own \`kit/\`.

`

const withHeader = (skillMd) => {
  const text = skillMd.replace(/\r\n/g, '\n')
  const end = text.indexOf('\n---\n', 4)
  if (!text.startsWith('---\n') || end === -1) throw new Error('SKILL.md without frontmatter')
  return text.slice(0, end + 5) + '\n' + SKILL_HEADER + text.slice(end + 5).replace(/^\n+/, '')
}

const anyHarness = `# Harness: any agent other than Claude Code

${NOTICE}

version: ${version}
agent: any
plugin-files: .sdlc/kit/

This is the package's own harness file. The repo's is \`.sdlc/kit/HARNESS.md\`, which \`sdlc-install\` writes from
\`kit/harness/<agent>.md\` for the agent you use. Until then, run \`sdlc-install\`.
`

const readme = `# leeway-sdlc for agents other than Claude Code

${NOTICE}

Generated by \`scripts/build-targets.mjs\` from \`plugin/\`; do not edit by hand. Supported: ${TARGETS.map((t) => t.name).join(', ')}.
Install with the commands in [agent-setup/prompt.md](../../agent-setup/prompt.md), then run the \`sdlc-install\` skill in the repo.
`

const build = (out) => {
  const agents = readdirSync(join(PLUGIN, 'agents')).filter((n) => n.endsWith('.md')).sort().map((n) => parseAgent(join(PLUGIN, 'agents', n)))
  const pkg = join(out, 'targets', 'agents')
  const kit = join(pkg, 'skills', 'sdlc-install', 'kit')

  // Skills, with the header. Templates and references copied byte for byte.
  for (const file of files(join(PLUGIN, 'skills'))) {
    const rel = relative(join(PLUGIN, 'skills'), file)
    const content = rel.endsWith(`${sep}SKILL.md`) || rel === 'SKILL.md' ? withHeader(readFileSync(file, 'utf8')) : readFileSync(file)
    write(join(pkg, 'skills', rel), content)
    // The kit mirrors the skills' own files for "in this plugin" paths, but never a SKILL.md: skill
    // installers scan for SKILL.md, and a second copy would show up as a duplicate skill.
    if (!rel.endsWith('SKILL.md')) write(join(kit, 'skills', rel), content)
  }

  // The kit.
  write(join(kit, 'PROCESS.md'), readFileSync(join(PLUGIN, 'PROCESS.md')))
  write(join(kit, 'HARNESS.md'), anyHarness)
  cpSync(join(PLUGIN, 'craft'), join(kit, 'craft'), { recursive: true })
  cpSync(join(PLUGIN, 'agents'), join(kit, 'agents'), { recursive: true })
  for (const f of ['git-guard.mjs', 'leeway-guard.mjs', 'adapters/guard.mjs', 'adapters/governed.mjs']) {
    write(join(kit, 'hooks', f), readFileSync(join(PLUGIN, 'hooks', f)))
  }
  for (const t of TARGETS) {
    write(join(kit, 'harness', `${t.id}.md`), harness(t, version, NOTICE))
    for (const [path, content] of Object.entries(t.wiring(agents))) write(join(kit, 'wiring', t.id, path), content)
  }

  // The package.
  write(join(pkg, 'HARNESS.md'), anyHarness)
  write(join(pkg, 'README.md'), readme)
  write(
    join(pkg, 'plugin.json'),
    JSON.stringify(
      {
        $schema: 'https://agent-plugins.org/schemas/1.0.0/plugin.schema.json',
        name: 'leeway-sdlc-agents',
        version,
        description: 'leeway-sdlc for agents other than Claude Code: the skills, and a kit sdlc-install copies into the repo with the subagents and the guard hooks.',
        author: { name: 'Shiny Ventures', url: 'https://github.com/leeway-run' },
      },
      null,
      2,
    ) + '\n',
  )

  write(join(out, 'agent-setup', 'prompt.md'), prompt())
}

const prompt = () => `# Leeway agent setup

You are setting up the user's coding agent to work with Leeway (https://leeway.run). Follow the steps in order.
Run commands from the root of the repo the user wants to set up. **Never ask for, read, print or write a Leeway
token.** Where a step says ASK, ask the user and wait for the answer.

leeway-sdlc has been tested with Claude Code only. If you are another agent, tell the user before step 3 that
support for their agent is built in but has not been verified yet, that verified support will come later, and
that issues go to https://github.com/leeway-run/leeway-sdlc/issues. Then carry on.

The snippet that sent you here may name a \`server\` and a \`product\`. Keep them for step 4.

## 1. The leeway CLI

If \`leeway --version\` works, skip this step. Otherwise ASK: install it globally
(\`npm i -g @leeway-run/cli\`), or run it through npx in this repo only (\`npx -y @leeway-run/cli\`, recorded as the \`cli:\` in step 4)?
Do what the user chooses. If \`node\` is missing, stop and tell the user Node.js is required.

## 2. Sign in

Run \`leeway whoami\`. If it is not signed in, tell the user to run \`leeway login\` themselves, adding
\`--server <url>\` if the snippet named a server other than https://app.leeway.run. In agents with a shell escape the
command is \`! leeway login\`. Wait, then run \`leeway whoami\` again.

## 3. Install leeway-sdlc for your agent

Use the section for the agent you are. Run the commands as written. Do not copy files by hand.

### Claude Code
\`\`\`
claude plugin marketplace add leeway-run/leeway-sdlc
claude plugin install leeway-sdlc@leeway --scope project
\`\`\`
Tell the user to run \`/reload-plugins\`.

${TARGETS.map(
  (t) => `### ${t.name}
${t.install.map((s) => `- ${s}`).join('\n')}

After step 4: ${t.after}
`,
).join('\n')}
### Any other agent
leeway-sdlc does not support it yet. Tell the user which agents it does support, and stop after step 2.

## 4. Bind the repo

Run the \`sdlc-install\` skill (Claude Code: \`/leeway-sdlc:sdlc-install\`). Give it the server and product from the
snippet, if it named them. It asks the rest, shows its plan, and writes nothing before the user agrees.

## Done

Show:

\`\`\`
Leeway agent setup complete
  ✓ leeway CLI        <leeway --version>
  ✓ signed in         <account from leeway whoami>
  ✓ leeway-sdlc       ${version} for <agent>
  ✓ repo bound to     <product key>
\`\`\`

Then list anything the user still has to do: the trust or restart step for the agent, from step 3. For any agent
other than Claude Code, end with: "leeway-sdlc is tested with Claude Code only so far. If something doesn't work,
please report it at https://github.com/leeway-run/leeway-sdlc/issues".
`

if (!check) {
  rmSync(join(ROOT, 'targets', 'agents'), { recursive: true, force: true })
  build(ROOT)
  console.log(`built targets/agents and agent-setup/prompt.md for leeway-sdlc ${version}`)
} else {
  const tmp = mkdtempSync(join(tmpdir(), 'leeway-sdlc-build-'))
  try {
    build(tmp)
    const drift = []
    for (const base of ['targets/agents', 'agent-setup']) {
      const fresh = files(join(tmp, base)).map((f) => posix(relative(tmp, f)))
      const committed = files(join(ROOT, base)).map((f) => posix(relative(ROOT, f)))
      for (const f of new Set([...fresh, ...committed])) {
        const a = existsSync(join(tmp, f)) ? readFileSync(join(tmp, f)) : null
        const b = existsSync(join(ROOT, f)) ? readFileSync(join(ROOT, f)) : null
        if (!a || !b || !a.equals(b)) drift.push(f)
      }
    }
    if (drift.length) {
      console.error(`generated files are out of date; run node scripts/build-targets.mjs:\n  ${drift.join('\n  ')}`)
      process.exit(1)
    }
    console.log('generated files are up to date')
  } finally {
    rmSync(tmp, { recursive: true, force: true })
  }
}
